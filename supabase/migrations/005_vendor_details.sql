-- =============================================================================
-- 005_vendor_details.sql — richer vendor records.
--
-- CONCEPT:
--   vendor_types  — admin-managed list (Products / Services / Activities …)
--                   so vendors can be filtered and messaged by type.
--   vendors gets:
--     vendor_code    human-readable ID, auto 'V0001', 'V0002'… (admin can
--                    overwrite it with an existing ID from old records)
--     vendor_type_id → vendor_types
--     offerings      free text: what they actually sell / do
--     address, office_phone (second line besides the WhatsApp `phone`), website
--   The old free-text `category` is superseded by type + offerings; its
--   contents are copied into `offerings` so nothing is lost.
--
-- Safe to run more than once.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Vendor types
-- -----------------------------------------------------------------------------
create table if not exists vendor_types (
  id         int generated by default as identity primary key,
  name       text not null unique,
  sort_order int  not null default 0,
  created_at timestamptz not null default now()
);
insert into vendor_types (name, sort_order) values
  ('Products', 1), ('Services', 2), ('Activities', 3)
on conflict (name) do nothing;

-- -----------------------------------------------------------------------------
-- next_vendor_code() — 'V' + 4-digit running number.
-- CONCEPT: a plain sequence could collide with a code an admin typed in by
-- hand (e.g. they entered 'V0005' manually, then the sequence reaches 5).
-- So we keep drawing numbers until we find one that's free.
-- -----------------------------------------------------------------------------
create sequence if not exists vendor_code_seq;

create or replace function next_vendor_code() returns text
language plpgsql as $$
declare
  v_code text;
begin
  loop
    v_code := 'V' || lpad(nextval('vendor_code_seq')::text, 4, '0');
    exit when not exists (select 1 from vendors where vendor_code = v_code);
  end loop;
  return v_code;
end $$;

-- -----------------------------------------------------------------------------
-- New vendor columns
-- -----------------------------------------------------------------------------
alter table vendors add column if not exists vendor_code    text;
alter table vendors add column if not exists vendor_type_id int references vendor_types(id) on delete set null;
alter table vendors add column if not exists offerings      text;
alter table vendors add column if not exists address        text;
alter table vendors add column if not exists office_phone   text;
alter table vendors add column if not exists website        text;

-- Give existing vendors codes in the order they were added.
do $$
declare r record;
begin
  for r in select id from vendors where vendor_code is null order by created_at, id loop
    update vendors set vendor_code = next_vendor_code() where id = r.id;
  end loop;
end $$;

alter table vendors alter column vendor_code set default next_vendor_code();
alter table vendors alter column vendor_code set not null;
create unique index if not exists vendors_vendor_code_key on vendors (vendor_code);
create index if not exists vendors_type_idx on vendors (vendor_type_id);

-- Carry the old free-text category over into offerings.
update vendors set offerings = category where offerings is null and category is not null;

-- -----------------------------------------------------------------------------
-- Lockdown (same rules as 003): no direct access with the publishable key.
-- -----------------------------------------------------------------------------
alter table vendor_types enable row level security;
revoke execute on function next_vendor_code() from public, anon, authenticated;
grant  execute on function next_vendor_code() to service_role;
