export const DICTS: Record<Lang, Dict> = { en, zh, ms };
export type TKey = keyof Dict;

/** Look up a phrase and fill its {placeholders}. Falls back to English. */
export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const phrase = DICTS[lang][key] ?? en[key];
  return vars ? phrase.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : phrase;
}

/** Date locale for a language (dates follow the chosen language too). */
export const localeOf = (lang: Lang) => LANGS.find((l) => l.code === lang)!.locale;
